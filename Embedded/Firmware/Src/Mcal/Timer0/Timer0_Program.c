#include "Timer0_Interface.h"
#include "Atmega128Register.h"
#include "MacroFunction.h"

/**
 * @fn mTimer0_Init_FastPWM
 * @brief Initializes Timer0 in 8-bit Fast PWM mode on pin PB4 (OC0).
 *        Configures prescaler clk/64 (~977 Hz). Initial duty cycle = 0% (Fan OFF).
 * @details Configures Timer0 for 8-bit Fast PWM,
 *          and a prescaler of 64. Configures PB4/OC0 as an output and
 *          keeps Timer0 interrupts disabled.
 * @note The PWM signal is generated by hardware without CPU polling.
 */


void mTimer0_Init_FastPWM(void)
{
/* Disconnect OC0 temporarily */
ClearBit(TCCR0_Reg, 5);
ClearBit(TCCR0_Reg, 4);

/* Clear Clock Select bits */
ClearBit(TCCR0_Reg, 2);
ClearBit(TCCR0_Reg, 1);
ClearBit(TCCR0_Reg, 0);

/* Clear Interrupt bits */
ClearBit(TIMSK_Reg, 0); 
ClearBit(TIMSK_Reg, 1); 

/* Set PB4 as Output */
SetBit(DDRB_Reg, 4);

/* Set PB4 LOW */
ClearBit(PORTB_Reg, 4);
OCR0_Reg = 0U; /* Initial Duty Cycle = 0% */

/* Set Timer0 to Fast PWM Mode */
SetBit(TCCR0_Reg, 6);
SetBit(TCCR0_Reg, 3);

/* Set Prescaler /64 */
ClearBit(TCCR0_Reg, 2);
SetBit(TCCR0_Reg, 0);
SetBit(TCCR0_Reg, 1);
}